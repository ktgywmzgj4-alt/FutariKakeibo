/// 読み取りの精度を測るための、**実物のレシート**の集まり。
///
/// ここに置くのは利用者が実際に撮ったレシートだけ。作った例は入れない
/// （それは `ReceiptParserTests` の回帰テストに置く）。正解率はここだけで数える
/// （`ReceiptScoreboardTests`）。
///
/// 写しは2種類ある。どちらで作ったかを `source` に持つ。
/// - 実機の読み取り結果: 実機の画面「読み取った文字を確認」に出た行を、並びのまま写した。
///   位置は行の順から当ててある
/// - 写真から組み直し: 写真と実機の結果から組み直した。1文字ずつの写しではない
///
/// **個人情報は除いた。** カード番号の末尾・承認番号・取引コード・担当者の名前は置き換えてある。
/// 店名・住所・電話・登録番号は店が公表しているものなので残す（店を見分ける手がかりになる）。
///
/// 正解の品名は、写真で読めたものはその文字、読めなかったものは読み取り結果の文字にしてある。
/// 品名は「似ていれば当たり」で比べるので、1〜2文字の読み違いは当たりに数える。
enum ReceiptCorpus {
    enum Source: String, Sendable {
        case deviceText = "実機の読み取り結果"
        case reconstructed = "写真から組み直し"
    }

    struct Expected: Sendable {
        /// 正解とみなす店名（支店名まで）。空白・記号・大文字と小文字の違いは見ない。
        var merchants: [String]
        /// チェーン名。読んだ店名にこれが入っていれば「チェーン名までは当たり」と数える。
        var chains: [String]
        var total: Int
        var date: Date
        var category: ExpenseCategory
        /// 品名と、値引きの前の値段。0円の行（セットの付け合わせ）は入れない。
        /// `nil` は「写しに全部の品がそろっていないので、明細は数えない」。
        var items: [(name: String, amount: Int)]?
    }

    struct Sample: Sendable {
        var name: String
        var source: Source
        /// 読み取った日。日付は「今日」から3年以内のものしか受け付けないため、撮った頃の日にする。
        var now: Date
        var lines: [RecognizedLine]
        var expected: Expected
    }

    static let calendar: Calendar = {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "Asia/Tokyo") ?? .current
        return calendar
    }()

    /// 精度を数えるときに使う全部。並びは撮った順。
    static var all: [Sample] {
        [
            tenhou, eqvoAugust, chavaty, manaNoMori, selfix, mcdonalds, konomiya,
            aeonSeptember, eqvoSeptember, eggsNThings, fujiSafari, misterDonut, aeonOctober
        ]
    }

    static func day(_ year: Int, _ month: Int, _ day: Int) -> Date {
        calendar.date(from: DateComponents(year: year, month: month, day: day)) ?? .distantPast
    }

    /// 読み取り結果を再現するための断片。x座標で品名と金額を分ける。
    static func line(
        _ text: String,
        x: Double = 0.08,
        width: Double = 0.5,
        y: Double,
        height: Double = 0.018
    ) -> RecognizedLine {
        RecognizedLine(text: text, minX: x, maxX: x + width, midY: y, height: height)
    }

    /// 右端に刷られた金額の断片。
    static func price(_ text: String, y: Double) -> RecognizedLine {
        RecognizedLine(text: text, minX: 0.74, maxX: 0.93, midY: y, height: 0.018)
    }

